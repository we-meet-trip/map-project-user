#!/bin/sh
# docs/diagrams/src 의 원본으로 라이트·다크 SVG 와 PNG(가로 1600px)를 다시 만든다.
# .dot 원본의 @토큰@ 은 공용 다이어그램 규칙의 팔레트 색으로 바꿔 그린다. .seq.json 은 scripts/seq.py 가 그린다.
# 필요: Graphviz(dot), rsvg-convert, python3, Pretendard 글꼴(SIL OFL, 시스템에 설치 — 저장소에 넣지 않는다).
# 쓰임: sh scripts/render_diagrams.sh
set -eu
cd "$(dirname "$0")/.."
SRC=docs/diagrams/src
OUT=docs/diagrams

palette() {
  case "$1" in
    light) set -- '#FFFFFF' '#1F2328' '#57606A' '#DDF4FF' '#0969DA' '#FFF8C5' '#9A6700' '#F6F8FA' '#57606A' '#FBEFFF' '#8250DF' ;;
    dark)  set -- '#0D1117' '#E6EDF3' '#8B949E' '#0C2D6B' '#58A6FF' '#3B2E00' '#D29922' '#161B22' '#8B949E' '#2B1D3D' '#A371F7' ;;
  esac
  sed -e "s/@BG@/$1/g" -e "s/@FG@/$2/g" -e "s/@LINE@/$3/g" \
      -e "s/@SVC_FILL@/$4/g" -e "s/@SVC_EDGE@/$5/g" \
      -e "s/@DB_FILL@/$6/g" -e "s/@DB_EDGE@/$7/g" \
      -e "s/@EXT_FILL@/$8/g" -e "s/@EXT_EDGE@/$9/g" \
      -e "s/@OPT_FILL@/${10}/g" -e "s/@OPT_EDGE@/${11}/g"
}

count=0
for f in "$SRC"/*.dot; do
  [ -e "$f" ] || continue
  name=$(basename "$f" .dot)
  for theme in light dark; do
    # Graphviz 가 남기는 생성기 판 주석은 그림에 필요 없어 지운다.
    palette "$theme" < "$f" | dot -Tsvg | sed '/<!-- Generated by graphviz/,/-->/d' > "$OUT/$name-$theme.svg"
    rsvg-convert -w 1600 "$OUT/$name-$theme.svg" -o "$OUT/$name-$theme.png"
    count=$((count + 1))
  done
done
for f in "$SRC"/*.seq.json; do
  [ -e "$f" ] || continue
  name=$(basename "$f" .seq.json)
  python3 scripts/seq.py "$f" "$OUT/$name"
  for theme in light dark; do
    rsvg-convert -w 1600 "$OUT/$name-$theme.svg" -o "$OUT/$name-$theme.png"
    count=$((count + 1))
  done
done
echo "rendered $count images"
